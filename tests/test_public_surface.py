def test_baldric_coding_public_surface_is_frozen() -> None:
    """Pin the explicit 139-name facade so split refactors cannot drop exports."""
    assert tuple(sorted(baldric_coding.__all__)) == EXPECTED
    module_names = sorted(
        name for name in baldric_coding.__all__ if isinstance(getattr(baldric_coding, name), types.ModuleType)
    )
    assert module_names == []
    assert len(baldric_coding.__all__) == 139

#!/usr/bin/env python3
"""Measure the structural baseline the rearchitecture plan quotes.

Usage:
    uv run python scripts/measure_structure.py            # human table
    uv run python scripts/measure_structure.py --json      # machine JSON

The plan (``docs/internal/plans/2026-11-12-structural-rearchitecture.md`` §1)
requires that every line/symbol/file count in the plan is generated by this
script and pasted, never hand-written, so the numbers cannot drift between the
plan and reality. This is deliberately a *measurement* tool, not a gate; the
gates live in ``check_structure.py`` / ``check_import_graph.py``.

Counts are ``splitlines()``-based (independent of line endings) and exclude
``__pycache__`` and vendored ``data`` directories, matching the scanners.
"""

from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
TESTS = ROOT / "tests"


def _py_files(base: Path) -> list[Path]:
    if not base.exists():
        return []
    return [
        path
        for path in sorted(base.rglob("*.py"))
        if "__pycache__" not in path.parts and "data" not in path.parts
    ]


def _line_count(path: Path) -> int:
    return len(path.read_text(encoding="utf-8").splitlines())


def _count_lines_and_files(base: Path) -> tuple[int, int]:
    files = _py_files(base)
    return len(files), sum(_line_count(path) for path in files)


def _module_path(rel: str) -> Path:
    return SRC / rel


def _class_method_count(path: Path, class_name: str) -> int:
    if not path.exists():
        return 0
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == class_name:
            return sum(1 for child in node.body if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)))
    return 0


def _all_count(path: Path) -> int:
    path = _module_path(str(path))
    if not path.exists():
        return 0
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign):
            targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
            if "__all__" in targets and isinstance(node.value, (ast.List, ast.Tuple)):
                return len(node.value.elts)
    return 0


def _scanner_rule_count() -> int:
    import importlib.util
    import sys

    name = "_measure_check_import_graph"
    spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / "check_import_graph.py")
    if spec is None or spec.loader is None:  # pragma: no cover - defensive
        return 0
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    try:
        spec.loader.exec_module(module)
        return len(module.RULES) + len(module.ALLOW_RULES)
    finally:
        sys.modules.pop(name, None)


def measure() -> dict[str, object]:
    """Return the measured baseline as JSON-serialisable data."""
    src_files, src_lines = _count_lines_and_files(SRC)
    test_files, test_lines = _count_lines_and_files(TESTS)
    runtime_dir = SRC / "baldric" / "runtime"
    rt_files, rt_lines = _count_lines_and_files(runtime_dir)
    tui_files, tui_lines = _count_lines_and_files(runtime_dir / "frontends" / "tui")
    session_py = runtime_dir / "session" / "session.py"
    runtime_init = runtime_dir / "__init__.py"
    platform_init = runtime_dir / "platform" / "__init__.py"
    return {
        "src": {"files": src_files, "lines": src_lines},
        "tests": {"files": test_files, "lines": test_lines},
        "runtime": {"files": rt_files, "lines": rt_lines},
        "frontends/tui": {"files": tui_files, "lines": tui_lines},
        "runtime/session/session.py": {
            "lines": _line_count(session_py) if session_py.exists() else 0,
            "methods": _class_method_count(session_py, "CodingSession"),
        },
        "runtime/__init__.py": {
            "lines": _line_count(runtime_init) if runtime_init.exists() else 0,
            "all": _all_count(Path("baldric/runtime/__init__.py")),
        },
        "runtime/platform/__init__.py": {
            "lines": _line_count(platform_init) if platform_init.exists() else 0,
            "all": _all_count(Path("baldric/runtime/platform/__init__.py")),
        },
        "check_import_graph": {"rules": _scanner_rule_count()},
    }


def _print_table(data: dict[str, object]) -> None:
    print("item\tvalue")
    for key, value in data.items():
        if isinstance(value, dict):
            detail = " ".join(f"{k}={v}" for k, v in value.items())
            print(f"{key}\t{detail}")
        else:
            print(f"{key}\t{value}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="emit machine JSON instead of a table")
    args = parser.parse_args()
    data = measure()
    if args.json:
        print(json.dumps(data, indent=2, sort_keys=True))
    else:
        _print_table(data)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
